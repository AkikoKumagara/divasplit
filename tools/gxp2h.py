#!/usr/bin/env python3
"""Embed compiled shaders (shaders/compiled/*.gxp) in the plugin as src/shaders_gxp.h.

    python3 tools/gxp2h.py

The .gxp files come from the installer, which compiles shaders/*.cg on the Vita
with the system's shader compiler (ur0:data/libshacccg.suprx) into
ux0:data/divasplit/shaders/. Copy them to shaders/compiled/ and run this when
a shader changes; with them built in, the plugin needs no compiler.
"""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'shaders', 'compiled')
out = os.path.join(here, '..', 'src', 'shaders_gxp.h')
lines = ['// generated by tools/gxp2h.py from shaders/compiled/*.gxp: do not edit',
         '#ifndef DIVASPLIT_SHADERS_GXP_H', '#define DIVASPLIT_SHADERS_GXP_H', '', '#include <stdint.h>', '']
for name in sorted(os.listdir(src)):
    if not name.endswith('.gxp'):
        continue
    data = open(os.path.join(src, name), 'rb').read()
    if data[:4] != b'GXP\0':
        sys.exit(f'{name}: not a GXP program')
    sym = 'GXP_' + name[:-4].upper()
    lines.append(f'// {name}, {len(data)} bytes')
    lines.append(f'static const uint8_t {sym}[{len(data)}] __attribute__((aligned(16))) = {{')
    for i in range(0, len(data), 16):
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
    lines.append('};')
    lines.append('')
lines.append('#endif')
open(out, 'w').write('\n'.join(lines) + '\n')
print(f'wrote {out}')
